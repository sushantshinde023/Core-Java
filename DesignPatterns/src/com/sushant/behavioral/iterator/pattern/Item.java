package com.sushant.behavioral.iterator.pattern;

public class Item {
	private final String name;
	private final int quantity;
	public Item(String name, int quantity) {
		super();
		this.name = name;
		this.quantity = quantity;
	}
	public String getName() {
		return name;
	}
	public int getQuantity() {
		return quantity;
	}
	
	

}
